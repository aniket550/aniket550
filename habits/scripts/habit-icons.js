// Copies the habit icons from Lucide (ISC licence) into www/habit-icons.js,
// so the app ships them without a bundler. Run after changing the list.
const fs = require("fs");
const path = require("path");

const NAMES = [
  "book-open", "droplet", "glass-water", "footprints", "activity", "bike",
  "dumbbell", "person-standing", "flower-2", "brain", "moon", "bed",
  "sun", "sprout", "leaf", "apple", "salad", "carrot",
  "pill", "coffee", "music", "guitar", "notebook-pen", "languages",
  "graduation-cap", "laptop", "palette", "piggy-bank", "heart", "smile",
  "phone-off", "cigarette-off", "wine-off", "shower-head", "brush-cleaning", "timer",
  "sparkles"
];

const dir = path.join(__dirname, "..", "node_modules", "lucide-static", "icons");
const icons = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(dir, n + ".svg"), "utf8");
  icons[n] = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).replace(/\s*\n\s*/g, "").trim();
}
const out = "// Generated by scripts/habit-icons.js from lucide-static (ISC licence, https://lucide.dev). Do not edit.\n" +
  "window.HABIT_ICONS = " + JSON.stringify(icons, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "www", "habit-icons.js"), out);
console.log("www/habit-icons.js: " + NAMES.length + " icons");
